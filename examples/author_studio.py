say('Este é um treino de conversação em inglês americano, com situações do dia a dia e de produção musical. Vamos falar sobre agora, ontem e amanhã. Não é uma prova de nível.')
say('Quando eu fizer uma pergunta, responda em voz alta durante a pausa, antes de ouvir a resposta. Se travar, tente uma frase curta. Depois, compare com o exemplo. Não precisa acertar tudo.')
say('Não leia o roteiro enquanto pratica. Você pode pausar a gravação se precisar de mais tempo. No final, haverá espaço para uma resposta pessoal, sem uma única resposta certa.')
say('Primeiro, ouça uma conversa. Não tente decorar.')
en('Hey! What are you working on?',kind='dialogue')
