#!/usr/bin/env python3
"""Author an original PT-BR → American English active-recall pilot."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent
segments=[]
chapter=''
def section(name):
    global chapter
    chapter=name

def say(text,lang='pt-BR',voice=None,kind='instruction',gap=0.6):
    segments.append(dict(id=f's{len(segments)+1:03d}',chapter=chapter,kind=kind,language=lang,voice=voice or ('pf_dora' if lang=='pt-BR' else 'af_bella'),text=text,gap_after_seconds=gap))
def en(text,voice='af_bella',kind='model',gap=.8):say(text,'en-US',voice,kind,gap)
def ask(prompt,answer,pause=6,language='pt-BR',voice='af_bella',variants=None,kind='recall'):
    say(prompt,language,kind=kind+'_prompt',gap=pause)
    segments[-1]['expected_answer']=answer
    segments[-1]['acceptable_variants']=variants or [answer]
    en(answer,voice,kind='confirmation',gap=.8)
def repeat(text,pause=5):
    en(text,kind='repeat_model',gap=pause)

